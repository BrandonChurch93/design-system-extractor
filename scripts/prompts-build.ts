// Turns packages/pipeline/src/models/prompts/*.md into a TypeScript module, so the worker, the CLI
// and tests load the same text without a file read at run time. A unit test keeps them in sync.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export const promptsDir = resolve(import.meta.dirname, '../packages/pipeline/src/models/prompts');
export const generatedFile = join(promptsDir, 'index.generated.ts');

export function renderPromptsModule(): string {
  const files = readdirSync(promptsDir).filter((f) => f.endsWith('.md')).sort();
  const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.md$/, ''))}: ${JSON.stringify(readFileSync(join(promptsDir, f), 'utf8'))},`);
  return `// Generated by \`pnpm prompts:build\` from the .md files beside it. Do not edit.\nexport const prompts = {\n${entries.join('\n')}\n} as const;\n\nexport type PromptName = keyof typeof prompts;\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(generatedFile, renderPromptsModule());
  console.log(`prompts:build · ${generatedFile}`);
}
